"""
Crop Feature Engine
-------------------
Main entry point for the rule-based feature selection engine.

After crop recommendations are generated by the rule engine,
this module matches recommended crop names against the additional
crop information dataset and retrieves mapped attributes.

Engine Logic:
  1. Receive recommended crop names from the recommendation pipeline
  2. Normalize crop names (case-insensitive, whitespace handling)
  3. Match against the Crop_Additional_Info.xlsx dataset
  4. Retrieve mapped information for matching crops
  5. Return structured data with graceful fallback for unmatched crops

No hardcoding — all data comes from the Excel dataset.
"""
from typing import Optional

from .crop_data_mapper import get_mapper
from .crop_feature_service import enrich_recommendations


def get_additional_crop_info(crop_name: str, location_name: Optional[str] = None) -> Optional[dict]:
    """
    Get additional information for a single crop by name.

    Args:
        crop_name: The name of the crop to look up
        location_name: Optional country/state name for scoped lookup

    Returns:
        Dict with keys: crop_duration, best_sowing_season, water_requirement,
        common_pests, recommended_fertilizers, harvest_time
        or None if not found.
    """
    mapper = get_mapper()
    return mapper.lookup(crop_name, location_name)


def enrich_crop_recommendations(top_crops: list, location_name: Optional[str] = None) -> list:
    """
    Enrich a list of top crop recommendations with additional info.

    This is the main function called after recommendations are generated.
    It processes every crop in the list and attaches matching data.

    Args:
        top_crops: List of crop result dicts from the recommendation pipeline
        location_name: Country/state name for scoped lookup

    Returns:
        The same list with each crop dict augmented with 'additional_info'
    """
    return enrich_recommendations(top_crops, location_name)
